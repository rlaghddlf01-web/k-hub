export interface HomeCopy {
  /** 상단 바로가기 글자 */
  nav: string;
  /** 서비스 카드 한 줄 소개 */
  card: string;
  /** 히어로 부제 (네 서비스를 모두 적은 것) */
  sub: string;
  detail: ServiceDetailCopy;
  /** "어떤 서비스가 맞을까요?" 에 더할 문장 */
  intents: string[];
  /** 이용 방법 2단계 글 (네 서비스를 모두 적은 것) */
  pickStep: string;
  /** 자주 묻는 질문 2번 질문 ("세 서비스" → 여러 서비스) */
  accountsQ: string;
}

const ICONS: IconKey[] = ['map', 'calc', 'shield', 'users', 'chat'];

function make(c: Omit<HomeCopy, 'detail'> & { eyebrow: string; headline: string; desc: string; features: [string, string][]; forWho: string[] }): HomeCopy {
  const { eyebrow, headline, desc, features, forWho, ...rest } = c;
  return { ...rest, detail: { eyebrow, headline, desc, forWho, features: features.map(([title, text], i) => ({ icon: ICONS[i], title, text })) } };
}

